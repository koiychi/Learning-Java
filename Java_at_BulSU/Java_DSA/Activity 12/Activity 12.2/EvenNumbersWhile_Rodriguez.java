public class EvenNumbersWhile_Rodriguez {
    public static void main(String[] args) {
        System.out.println("Even numbers from 2 to 100 (while loop): ");
        int i = 2;
        while (i <= 100) {
            System.out.print(i + " ");
            i += 2;
        }

        System.out.println();
    }
}
